"""Generate the one-shot Daz Script (.dsa) that a worker instance executes.

The script is deliberately small, because the DS6 script API drifts between
betas (see RENDERQUEUE_MANAGER.md, rule 4). It:

1. opens the scene, merges the post-loader presets, waits briefly to settle,
2. looks the camera up by label (headless DAZ has no viewport camera),
3. points the render options at the target file and renders synchronously,
4. writes a small JSON result file so the manager can tell a clean finish from
   a crash or a suppressed dialog (both leave no result file).

String literals are emitted through json.dumps, which produces valid
ECMAScript string syntax for any path. Paths are normalised to forward slashes.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path, PureWindowsPath
from typing import List, Optional

META_PREFIX = "// PANDALOADER-META "


def _posix(path: str) -> str:
    return PureWindowsPath(path).as_posix()


def _js(value) -> str:
    """A JavaScript literal for str/int/float/bool/None."""
    return json.dumps(value)


@dataclass
class JobSpec:
    scene_file: str
    target: str
    camera_label: str
    result_file: str
    post_loaders: List[str] = field(default_factory=list)
    image_size: Optional[tuple] = None     # (w, h); None keeps the preset/scene size
    settle_wait_s: int = 3
    frame: int = 0
    scene_index: int = -1
    label: str = ""

    def meta(self) -> dict:
        return {
            "scene": _posix(self.scene_file), "target": _posix(self.target), "camera": self.camera_label,
            "result": _posix(self.result_file), "postLoaders": [_posix(p) for p in self.post_loaders],
            "imageSize": list(self.image_size) if self.image_size else None, "frame": self.frame,
            "sceneIndex": self.scene_index, "label": self.label,
        }


def parse_meta(script_text: str) -> Optional[dict]:
    """Recover the JobSpec metadata from a generated script (used by tests and tools)."""
    for line in script_text.splitlines():
        if line.startswith(META_PREFIX):
            return json.loads(line[len(META_PREFIX):])
    return None


def render_script(spec: JobSpec) -> str:
    scene = _js(_posix(spec.scene_file))
    target = _js(_posix(spec.target))
    result = _js(_posix(spec.result_file))
    camera = _js(spec.camera_label)
    presets = ", ".join(_js(_posix(p)) for p in spec.post_loaders)
    size_line = ""
    if spec.image_size:
        w, h = int(spec.image_size[0]), int(spec.image_size[1])
        size_line = f"  opt.isAspectConstrained = false; opt.imageSize = new Size({w}, {h});\n"

    lines = [
        META_PREFIX + json.dumps(spec.meta()),
        "// Generated by PandaLoader. One render job for a headless DAZ Studio 6 worker.",
        "var R = { ok: false, stage: \"start\", error: \"\", renderReturned: null, cameraFound: false,",
        "          imageSize: \"\", outputExists: false, outputSize: 0, t: {} };",
        "var T0 = new Date().getTime();",
        "function now() { return (new Date().getTime() - T0) / 1000; }",
        "function writeResult() {",
        f"  try {{ var f = new DzFile({result}); f.open(DzFile.WriteOnly); f.write(JSON.stringify(R)); f.close(); }} catch (e) {{}}",
        "}",
        "function waitSecs(n) {",
        "  var until = new Date().getTime() + n * 1000;",
        "  while (new Date().getTime() < until) { processEvents(); sleep(100); }",
        "}",
        "function dim(sz, k) { var v = sz[k]; if (typeof v === \"function\") { v = sz[k](); } return v; }",
        "try {",
        "  var cm = App.getContentMgr();",
        "  var mgr = App.getRenderMgr();",
        "  R.stage = \"load\";",
        f"  if (!cm.openFile({scene}, false)) {{ throw \"openFile failed: \" + {scene}; }}",
        "  R.t.load = now();",
        f"  var presets = [{presets}];",
        "  for (var i = 0; i < presets.length; i++) {",
        "    R.stage = \"preset\";",
        "    if (!cm.openFile(presets[i], true)) { throw \"preset merge failed: \" + presets[i]; }",
        "  }",
        f"  waitSecs({int(spec.settle_wait_s)});",
        "  R.stage = \"camera\";",
        f"  var cam = Scene.findCameraByLabel({camera});",
        f"  if (!cam) {{ throw \"camera not found: \" + {camera}; }}",
        "  R.cameraFound = true;",
        "  var opt = mgr.getRenderOptions();",
        size_line.rstrip("\n") if size_line else "  // image size: as set by the scene / preset",
        "  opt.renderImgToId = DzRenderOptions.DirectToFile;",
        f"  opt.renderImgFilename = {target};",
        "  var w = dim(opt.imageSize, \"width\"), h = dim(opt.imageSize, \"height\");",
        "  R.imageSize = w + \"x\" + h;",
        "  R.stage = \"render\";",
        f"  var handler = new DzImageRenderHandler(new Size(w, h), {int(spec.frame)}, {target});",
        "  var r = mgr.getActiveRenderer().render(handler, cam, opt);",
        "  R.renderReturned = r;",
        "  R.t.render = now();",
        "  var waited = 0;",
        "  while (mgr.isRendering() && waited < 120) { waitSecs(1); waited++; }",
        f"  var fi = new DzFileInfo({target});",
        "  R.outputExists = fi.exists();",
        "  R.outputSize = fi.exists() ? fi.size() : 0;",
        "  R.ok = (r === true || r === 1) && R.outputExists;",
        "  R.stage = \"done\";",
        "} catch (e) {",
        "  R.error = \"\" + e;",
        "}",
        "R.t.total = now();",
        "writeResult();",
        "",
    ]
    return "\n".join(lines)


def write_job(spec: JobSpec, path) -> Path:
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(render_script(spec), encoding="utf-8")
    return p
